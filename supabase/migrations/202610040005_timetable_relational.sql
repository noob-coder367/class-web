-- Check existing FK definitions and add only the exact BIGINT -> BIGINT relation.
-- NOT VALID preserves historical orphan rows but enforces future writes.
do $$
declare
  child_table text;
  child_attnum smallint;
  parent_attnum smallint;
  wrong_fk boolean;
  incompatible_delete boolean;
begin
  select attnum into parent_attnum from pg_attribute
  where attrelid='public.timetables'::regclass and attname='id' and attnum > 0 and not attisdropped;

  foreach child_table in array array[
    'timetable_sessions','timetable_periods','timetable_breaks',
    'timetable_entries','timetable_change_notices'
  ] loop
    select attnum into child_attnum from pg_attribute
    where attrelid=format('public.%I',child_table)::regclass
      and attname='timetable_id' and attnum > 0 and not attisdropped;

    select exists (
      select 1 from pg_constraint c
      where c.conrelid=format('public.%I',child_table)::regclass and c.contype='f'
        and c.conkey=array[child_attnum]::smallint[]
        and (c.confrelid <> 'public.timetables'::regclass or c.confkey <> array[parent_attnum]::smallint[])
    ) into wrong_fk;
    if wrong_fk then
      raise exception 'public.%.timetable_id already has an unrelated FK; inspect it without dropping data.', child_table;
    end if;

    select exists (
      select 1 from pg_constraint c
      where c.conrelid=format('public.%I',child_table)::regclass and c.contype='f'
        and c.conkey=array[child_attnum]::smallint[]
        and c.confrelid='public.timetables'::regclass and c.confkey=array[parent_attnum]::smallint[]
        and c.confdeltype <> 'c'
    ) into incompatible_delete;
    if incompatible_delete then
      raise exception 'public.%.timetable_id references timetables.id but does not use ON DELETE CASCADE; inspect before retrying.', child_table;
    end if;

    if not exists (
      select 1 from pg_constraint c
      where c.conrelid=format('public.%I',child_table)::regclass and c.contype='f'
        and c.conkey=array[child_attnum]::smallint[]
        and c.confrelid='public.timetables'::regclass and c.confkey=array[parent_attnum]::smallint[]
    ) then
      execute format(
        'alter table public.%I add constraint %I foreign key (timetable_id) references public.timetables(id) on delete cascade not valid',
        child_table, child_table || '_timetable_id_fkey'
      );
    end if;
  end loop;
end $$;

-- Unique keys used by the backfill's ON CONFLICT targets. Duplicate legacy rows
-- cause an explicit index-creation error; the transaction rolls back, no rows are
-- deleted or merged. Existing equivalent unique indexes are reused.
do $$
declare
  expected record;
  rel regclass;
  key_attnums smallint[];
  has_unique boolean;
  key_count integer;
begin
  for expected in select * from (values
    ('timetables','timetables_class_name_uidx','class_name'),
    ('timetable_sessions','timetable_sessions_timetable_session_uidx','timetable_id,session'),
    ('timetable_periods','timetable_periods_timetable_session_period_uidx','timetable_id,session,period_id'),
    ('timetable_breaks','timetable_breaks_timetable_session_after_uidx','timetable_id,session,after_period'),
    ('timetable_entries','timetable_entries_timetable_session_day_period_uidx','timetable_id,session,day_id,period_id'),
    ('timetable_change_notices','timetable_change_notices_timetable_uidx','timetable_id')
  ) as expected(table_name,index_name,column_list)
  loop
    rel := to_regclass(format('public.%I',expected.table_name));
    select array_agg(a.attnum::smallint order by cols.ordinality)
      into key_attnums
    from unnest(string_to_array(expected.column_list,',')) with ordinality as cols(column_name,ordinality)
    join pg_attribute a on a.attrelid=rel and a.attname=cols.column_name
      and a.attnum > 0 and not a.attisdropped;
    key_count := cardinality(key_attnums);
    if key_count <> cardinality(string_to_array(expected.column_list,',')) then
      raise exception 'Cannot create %: a required key column is missing.', expected.index_name;
    end if;

    select exists (
      select 1 from pg_index i
      where i.indrelid=rel and i.indisunique and i.indisvalid
        and i.indpred is null and i.indexprs is null
        and i.indnkeyatts=key_count and i.indnatts=key_count
        and array(select i.indkey[positions.pos]::smallint
          from generate_series(0,key_count-1) as positions(pos))=key_attnums
    ) into has_unique;
    if not has_unique then
      execute format('create unique index %I on public.%I (%s)',
        expected.index_name,expected.table_name,expected.column_list);
    end if;
  end loop;
end $$;

