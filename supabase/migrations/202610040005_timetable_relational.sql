-- Fail clearly on any incompatible or incomplete partial-state ID column; never
-- ALTER its type or replace its values. Each timetable_id FK must be BIGINT -> BIGINT; existing child IDs are preserved.
do $$
declare
  child_table text;
  child_id_type text;
  fk_type text;
  null_fk_rows bigint;
  invalid_key_rows bigint;
  parent_attnum smallint;
begin
  select attnum into parent_attnum from pg_attribute
  where attrelid='public.timetables'::regclass and attname='id' and attnum > 0 and not attisdropped;
  if parent_attnum is null then
    raise exception 'public.timetables.id is missing; no ID column was added or generated.';
  end if;

  foreach child_table in array array[
    'timetable_sessions','timetable_periods','timetable_breaks',
    'timetable_entries','timetable_change_notices'
  ] loop
    select format_type(a.atttypid,a.atttypmod) into child_id_type
    from pg_attribute a where a.attrelid=format('public.%I',child_table)::regclass
      and a.attname='id' and a.attnum > 0 and not a.attisdropped;
    if child_table = 'timetable_sessions' then
      if child_id_type is distinct from 'uuid' then
        raise exception 'public.%.id must remain UUID; found %. No conversion was attempted.', child_table, coalesce(child_id_type,'<missing>');
      end if;
    elsif child_id_type is distinct from 'bigint' then
      raise exception 'public.%.id must remain BIGINT; found %. No conversion was attempted.', child_table, coalesce(child_id_type,'<missing>');
    end if;

    select format_type(a.atttypid,a.atttypmod) into fk_type
    from pg_attribute a where a.attrelid=format('public.%I',child_table)::regclass
      and a.attname='timetable_id' and a.attnum > 0 and not a.attisdropped;
    if fk_type is distinct from 'bigint' then
      raise exception 'public.%.timetable_id must be BIGINT to match public.timetables.id; found %. No conversion or row deletion was attempted.',
        child_table, coalesce(fk_type,'<missing>');
    end if;

    execute format('select count(*) from public.%I where timetable_id is null',child_table) into null_fk_rows;
    if null_fk_rows > 0 then
      raise exception 'public.%.timetable_id has % NULL rows; inspect this partial table before adding its required FK.', child_table, null_fk_rows;
    end if;
    execute format('alter table public.%I alter column timetable_id set not null',child_table);
  end loop;

  if exists (select 1 from public.timetable_sessions where session is null) then
    raise exception 'public.timetable_sessions contains NULL session keys; inspect existing rows before retrying.';
  end if;
  if exists (select 1 from public.timetable_periods where session is null or period_id is null) then
    raise exception 'public.timetable_periods contains NULL natural-key values; inspect existing rows before retrying.';
  end if;
  if exists (select 1 from public.timetable_breaks where session is null or after_period is null) then
    raise exception 'public.timetable_breaks contains NULL natural-key values; inspect existing rows before retrying.';
  end if;
  if exists (select 1 from public.timetable_entries where session is null or day_id is null or period_id is null) then
    raise exception 'public.timetable_entries contains NULL natural-key values; inspect existing rows before retrying.';
  end if;
  select count(*) into invalid_key_rows from public.timetable_periods
    where period_id not between 1 and 8;
  if invalid_key_rows > 0 then
    raise exception 'public.timetable_periods has % period_id values outside 1..8; no rows were changed.', invalid_key_rows;
  end if;
  select count(*) into invalid_key_rows from public.timetable_breaks
    where after_period not between 1 and 8;
  if invalid_key_rows > 0 then
    raise exception 'public.timetable_breaks has % after_period values outside 1..8; no rows were changed.', invalid_key_rows;
  end if;
  select count(*) into invalid_key_rows from public.timetable_entries
    where period_id not between 1 and 8 or day_id not in ('t2','t3','t4','t5','t6','t7');
  if invalid_key_rows > 0 then
    raise exception 'public.timetable_entries has % invalid day/period key values; no rows were changed.', invalid_key_rows;
  end if;
end $$;

