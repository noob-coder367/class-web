-- Persist the PDF-derived class roster used by the legacy Tiện ích workflow.
create table if not exists public.utility_rosters (
  id text primary key check (id = 'default'),
  file_name text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.utility_roster_members (
  id bigint generated by default as identity primary key,
  roster_id text not null default 'default' references public.utility_rosters(id) on delete cascade,
  student_number integer not null check (student_number > 0),
  name text not null check (char_length(trim(name)) between 1 and 160),
  position integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists utility_roster_members_position_idx
  on public.utility_roster_members (roster_id, position);

insert into public.utility_rosters (id, file_name)
values ('default', '')
on conflict (id) do nothing;

create or replace function public.replace_utility_roster(
  p_file_name text,
  p_updated_at timestamptz,
  p_names jsonb
) returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if jsonb_typeof(p_names) <> 'array' then
    raise exception 'UTILITY_ROSTER_NAMES_MUST_BE_ARRAY';
  end if;
  if jsonb_array_length(p_names) < 1 or jsonb_array_length(p_names) > 100 then
    raise exception 'UTILITY_ROSTER_SIZE_INVALID';
  end if;

  insert into public.utility_rosters (id, file_name, updated_at)
  values ('default', left(coalesce(nullif(trim(p_file_name), ''), 'danh-sach.pdf'), 240), coalesce(p_updated_at, now()))
  on conflict (id) do update
    set file_name = excluded.file_name, updated_at = excluded.updated_at;

  delete from public.utility_roster_members where roster_id = 'default';

  insert into public.utility_roster_members (roster_id, student_number, name, position)
  select 'default',
         coalesce(nullif((item->>'stt')::integer, 0), ordinality::integer),
         left(trim(item->>'name'), 160),
         ordinality::integer
  from jsonb_array_elements(p_names) with ordinality as roster(item, ordinality)
  where nullif(trim(item->>'name'), '') is not null;
end;
$$;

alter table public.utility_rosters enable row level security;
alter table public.utility_roster_members enable row level security;
revoke all on public.utility_rosters, public.utility_roster_members from public, anon, authenticated;
grant all on public.utility_rosters, public.utility_roster_members to service_role;
revoke all on function public.replace_utility_roster(text, timestamptz, jsonb) from public, anon, authenticated;
grant execute on function public.replace_utility_roster(text, timestamptz, jsonb) to service_role;
notify pgrst, 'reload schema';
